import {
  ACTIVITY_LEVELS,
  DIET_PREFERENCES,
  GOALS,
  MEAL_SLOTS,
  type AssessmentDraft,
} from '../data/assessment'
import { estimateTargets } from '../data/targets'
import '../styles/personalization.css'

const labelFrom = <T extends { id: string; label: string }>(options: readonly T[], id: string) =>
  options.find((option) => option.id === id)?.label ?? ''

/* An illustrative example used to show how the inputs shape the plan.
   The numbers are generated by the same calculation module the app uses —
   they are not hardcoded marketing figures. */
const EXAMPLE_DRAFT: AssessmentDraft = {
  age: '28',
  heightCm: '178',
  currentWeightKg: '70',
  activityLevel: 'active',
  targetWeightKg: '75',
  goal: 'muscle-gain',
  dietPreference: 'non-vegetarian',
  restrictions: [],
  otherRestrictions: '',
  mealSlots: ['breakfast', 'lunch', 'dinner'],
}

export function Personalization() {
  const example = estimateTargets(EXAMPLE_DRAFT)

  const inputs = [
    { term: 'Goal', detail: labelFrom(GOALS, EXAMPLE_DRAFT.goal) },
    { term: 'Target weight', detail: `${EXAMPLE_DRAFT.targetWeightKg} kg` },
    { term: 'Activity', detail: labelFrom(ACTIVITY_LEVELS, EXAMPLE_DRAFT.activityLevel) },
    { term: 'Diet', detail: labelFrom(DIET_PREFERENCES, EXAMPLE_DRAFT.dietPreference) },
    {
      term: 'Meal slots',
      detail: EXAMPLE_DRAFT.mealSlots.map((id) => labelFrom(MEAL_SLOTS, id)).join(' · '),
    },
  ]

  return (
    <section className="site-section site-section--tinted" aria-labelledby="personal-title">
      <div className="site-container">
        <div className="personal-grid">
          <div>
            <p className="site-eyebrow">Personalization</p>
            <h2 id="personal-title">Five inputs, one week of meals.</h2>
            <p className="personal-lede">
              Your goal, target weight, activity, diet, and meal schedule set the portion sizes,
              protein, and the dishes that appear in your week.
            </p>
            <dl className="personal-inputs">
              {inputs.map((input) => (
                <div key={input.term}>
                  <dt>{input.term}</dt>
                  <dd>{input.detail}</dd>
                </div>
              ))}
            </dl>
          </div>

          <aside className="personal-example">
            <p className="personal-example__label">Example estimate</p>
            {example ? (
              <>
                <p className="personal-example__value">
                  {example.calories}
                  <span> kcal / day</span>
                </p>
                <p className="personal-example__macros">
                  {example.proteinGrams} g protein · {example.carbsGrams} g carbs ·{' '}
                  {example.fatGrams} g fat
                </p>
              </>
            ) : null}
            <p className="personal-example__note">
              Generated from the example inputs above by the same estimator used in your plan —
              illustrative, not a prescription, and not your numbers until you finish the
              assessment.
            </p>
          </aside>
        </div>
      </div>
    </section>
  )
}